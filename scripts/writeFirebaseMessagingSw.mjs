import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

function loadEnvFile(rootDir) {
  try {
    const text = readFileSync(resolve(rootDir, '.env'), 'utf8')
    for (const line of text.split('\n')) {
      const trimmed = line.trim()
      if (!trimmed || trimmed.startsWith('#')) continue
      const eq = trimmed.indexOf('=')
      if (eq <= 0) continue
      const key = trimmed.slice(0, eq).trim()
      const value = trimmed.slice(eq + 1).trim()
      if (!(key in process.env)) process.env[key] = value
    }
  } catch {
    // .env is optional when CI already injected the variables.
  }
}

/** Writes public/firebase-messaging-sw.js with the current Firebase web config. */
export function writeFirebaseMessagingSw(rootDir = process.cwd()) {
  loadEnvFile(rootDir)
  const projectId = process.env.NUXT_PUBLIC_FIREBASE_PROJECT_ID || ''
  const config = {
    apiKey: process.env.NUXT_PUBLIC_FIREBASE_API_KEY || '',
    authDomain: process.env.NUXT_PUBLIC_FIREBASE_AUTH_DOMAIN || (projectId ? `${projectId}.firebaseapp.com` : ''),
    projectId,
    storageBucket: process.env.NUXT_PUBLIC_FIREBASE_STORAGE_BUCKET || (projectId ? `${projectId}.firebasestorage.app` : ''),
    messagingSenderId: process.env.NUXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID || '',
    appId: process.env.NUXT_PUBLIC_FIREBASE_APP_ID || ''
  }

  // A new name per build, so every deploy installs a fresh worker and clears the old cache.
  const buildId = process.env.BHAKTIRAS_BUILD_ID || Date.now().toString(36)
  const source = `/* Generated by scripts/writeFirebaseMessagingSw.mjs — do not edit by hand. */
importScripts('https://www.gstatic.com/firebasejs/11.0.2/firebase-app-compat.js')
importScripts('https://www.gstatic.com/firebasejs/11.0.2/firebase-messaging-compat.js')

firebase.initializeApp(${JSON.stringify(config, null, 2)})

const messaging = firebase.messaging()

function absoluteUrl(path) {
  try {
    return new URL(path || '/', self.location.origin).href
  } catch {
    return self.location.origin + '/'
  }
}

messaging.onBackgroundMessage((payload) => {
  const data = payload.data || {}
  const notification = payload.notification || {}
  const title = notification.title || data.title || 'Bhaktiras'
  const fullBody = notification.body || data.body || ''
  const preview = data.preview || fullBody
  const body = preview.length > 120 ? preview.slice(0, 119).trimEnd() + '…' : preview
  const options = {
    body,
    icon: '/notification-icon.png',
    badge: '/notification-badge.png',
    data: { url: absoluteUrl(data.url) },
    tag: data.tag || 'bhaktiras-update',
    renotify: true
  }
  return self.registration.showNotification(title, options)
})

/**
 * Offline support. Chromium also only offers "Install app" when a registered
 * service worker has a fetch handler, and push and caching must share this one
 * worker: registering a second at '/' would replace it and silently kill push.
 *
 * Deliberately narrow, so it can never serve a stale site:
 * - hashed build files (\`/_nuxt/<hash>.js\`) and game images never change, so
 *   they are served from cache first;
 * - pages always go to the network, and the last good copy is used only when
 *   the network fails, with a small offline page if nothing was cached;
 * - everything else (Firebase, Flickr, the Chalisa's range requests, the
 *   server's /api routes) passes straight through;
 * - local development is never cached, so hot reload keeps working.
 * Each build gets its own cache name, and activating a new worker drops the old.
 */
const CACHE = 'bhaktiras-${buildId}'
const PAGE_LIMIT = 40
const OFFLINE_HTML = \`<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Offline · Bhaktiras</title><body style="margin:0;font-family:system-ui,sans-serif;background:#fdfcf9;color:#3D0066;display:grid;place-items:center;min-height:100vh;text-align:center;padding:24px"><div><h1 style="font-size:22px">You are offline</h1><p style="color:#555">Bhaktiras needs a connection for this page. Pages you have opened before still work offline.</p><p><a href="/play" style="color:#0369a1;font-weight:600">Open the games</a></p></div></body></html>\`
const isLocal = ['localhost', '127.0.0.1', '[::1]'].includes(self.location.hostname)

self.addEventListener('install', () => self.skipWaiting())

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys()
    await Promise.all(names.filter(name => name.startsWith('bhaktiras-') && name !== CACHE).map(name => caches.delete(name)))
    await self.clients.claim()
  })())
})

function isImmutableAsset(url) {
  if (/^\\/_nuxt\\/[^/]+\\.(js|css|woff2?)$/.test(url.pathname)) return true
  return url.pathname.startsWith('/games/') && /\\.(webp|png|jpe?g|svg)$/.test(url.pathname)
}

async function trimPages(cache) {
  const keys = await cache.keys()
  const pages = keys.filter(request => !isImmutableAsset(new URL(request.url)))
  for (const request of pages.slice(0, Math.max(0, pages.length - PAGE_LIMIT))) await cache.delete(request)
}

async function cacheFirst(request) {
  const cache = await caches.open(CACHE)
  const hit = await cache.match(request)
  if (hit) return hit
  const response = await fetch(request)
  if (response.ok && response.type === 'basic') await cache.put(request, response.clone())
  return response
}

async function networkFirstPage(request) {
  const cache = await caches.open(CACHE)
  try {
    const response = await fetch(request)
    if (response.ok && response.type === 'basic') {
      await cache.put(request, response.clone())
      await trimPages(cache)
    }
    return response
  } catch (error) {
    const hit = await cache.match(request, { ignoreSearch: true })
    if (hit) return hit
    return new Response(OFFLINE_HTML, { status: 503, headers: { 'Content-Type': 'text/html; charset=utf-8' } })
  }
}

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (isLocal || request.method !== 'GET') return
  const url = new URL(request.url)
  if (url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return
  if (request.mode === 'navigate') {
    event.respondWith(networkFirstPage(request))
  } else if (isImmutableAsset(url)) {
    event.respondWith(cacheFirst(request))
  }
})

self.addEventListener('notificationclick', (event) => {
  event.notification.close()
  const target = absoluteUrl(event.notification.data?.url || '/')
  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((clients) => {
      const existing = clients.find((client) => typeof client.focus === 'function')
      if (existing) {
        existing.navigate?.(target)
        return existing.focus()
      }
      return self.clients.openWindow(target)
    })
  )
})
`

  // A blank config produces a service worker that registers cleanly and can
  // never receive a push — no build error, nothing visibly wrong on the site.
  // So an incomplete config must never reach disk.
  //
  // The file is generated rather than committed (see .gitignore). It used to be
  // checked in, which meant any local build without .env rewrote it with empty
  // strings, and committing that shipped dead push to the whole sangat. Keeping
  // it out of git means the only copy that can reach production is the one CI
  // generates, and the throw below guarantees CI had real config to generate it
  // from.
  const missing = Object.entries(config).filter(([, value]) => !value).map(([key]) => key)
  if (missing.length) {
    const detail = `missing Firebase config (${missing.join(', ')}); `
      + 'populate .env or the NUXT_PUBLIC_FIREBASE_* environment variables'
    if (process.env.CI) {
      throw new Error(`Refusing to write public/firebase-messaging-sw.js: ${detail}.`)
    }
    console.warn(`[push] Skipped public/firebase-messaging-sw.js: ${detail}.`)
    return
  }

  writeFileSync(resolve(rootDir, 'public/firebase-messaging-sw.js'), source)
}
