/**
 * Bundles the game pickers and replays (`utils/gameVerify.ts`) into
 * `functions/shared/gameVerify.mjs`, so the Cloud Functions score a play with
 * the same code the pages use to choose the puzzle. Runs before every functions
 * deploy (`firebase.json` predeploy). The output is generated: edit the source.
 */
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

await build({
  entryPoints: [resolve(root, 'utils/gameVerify.ts')],
  outfile: resolve(root, 'functions/shared/gameVerify.mjs'),
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  alias: { '~': root },
  legalComments: 'none',
  logLevel: 'warning',
  banner: { js: '// Generated by scripts/buildFunctionsShared.mjs from utils/gameVerify.ts. Do not edit.' }
})
